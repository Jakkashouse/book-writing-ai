def make_styles():
    styles = {}
    styles["cover_brand"] = ParagraphStyle(
        "cover_brand", fontName="NanumBold", fontSize=13, textColor=white,
        alignment=TA_CENTER, leading=18, spaceAfter=10,
    )
    styles["cover_no"] = ParagraphStyle(
        "cover_no", fontName="NanumEB", fontSize=15, textColor=white,
        alignment=TA_CENTER, leading=20, spaceAfter=14,
    )
    styles["cover_title"] = ParagraphStyle(
        "cover_title", fontName="NanumEB", fontSize=24, textColor=white,
        alignment=TA_CENTER, leading=36, spaceAfter=16,
    )
    styles["cover_sub"] = ParagraphStyle(
        "cover_sub", fontName="NanumBold", fontSize=14, textColor=white,
        alignment=TA_CENTER, leading=22,
    )
    styles["cover_footer"] = ParagraphStyle(
        "cover_footer", fontName="Nanum", fontSize=11, textColor=white,
        alignment=TA_CENTER, leading=16,
    )
    styles["h_chapter"] = ParagraphStyle(
        "h_chapter", fontName="NanumBold", fontSize=11, textColor=white,
        alignment=TA_LEFT, leading=15, spaceAfter=6,
    )
    styles["h_title"] = ParagraphStyle(
        "h_title", fontName="NanumEB", fontSize=22, textColor=white,
        alignment=TA_LEFT, leading=32, spaceAfter=8,
    )
    styles["h_sub"] = ParagraphStyle(
        "h_sub", fontName="NanumBold", fontSize=14, textColor=white,
        alignment=TA_LEFT, leading=22, spaceAfter=18,
    )
    styles["body"] = ParagraphStyle(
        "body", fontName="Nanum", fontSize=13, textColor=white,
        alignment=TA_JUSTIFY, leading=24, spaceAfter=14, firstLineIndent=0,
    )
    styles["quote"] = ParagraphStyle(
        "quote", fontName="NanumBold", fontSize=14, textColor=white,
        alignment=TA_CENTER, leading=24, spaceBefore=22, spaceAfter=14,
        borderPadding=12, leftIndent=12, rightIndent=12,
    )
    styles["closing_label"] = ParagraphStyle(
        "closing_label", fontName="NanumBold", fontSize=11, textColor=white,
        alignment=TA_CENTER, leading=16, spaceBefore=26, spaceAfter=6,
    )
    styles["closing_msg"] = ParagraphStyle(
        "closing_msg", fontName="Nanum", fontSize=12, textColor=white,
        alignment=TA_CENTER, leading=20,
    )
    return styles


def cover_page(canvas_, doc, ch):
    canvas_.saveState()
    w, h = A4
    # 짙은 녹색 단색 배경
    canvas_.setFillColor(HexColor("#1A3309"))
    canvas_.rect(0, 0, w, h, fill=1, stroke=0)
    # 위아래 흰색 얇은 라인 (단정한 액자 느낌)
    canvas_.setStrokeColor(white)
    canvas_.setLineWidth(0.7)
    canvas_.line(25 * mm, h - 18 * mm, w - 25 * mm, h - 18 * mm)
    canvas_.line(25 * mm, 18 * mm, w - 25 * mm, 18 * mm)
    canvas_.restoreState()


def body_page(canvas_, doc):
    canvas_.saveState()
    w, h = A4
    # 본문도 동일한 짙은 녹색 배경
    canvas_.setFillColor(HexColor("#1A3309"))
    canvas_.rect(0, 0, w, h, fill=1, stroke=0)
    # 페이지 번호 (흰색)
    canvas_.setFillColor(white)
    canvas_.setFont("Nanum", 9)
    canvas_.drawCentredString(w / 2, 12 * mm, f"- {doc.page} -")
    canvas_.restoreState()


def build_pdf(ch):
    safe_title = re.sub(r'[\\/:*?"<>|]', "_", ch["title"])[:40]
    fname = f"{ch['no']:02d}_{safe_title}.pdf"
    fpath = os.path.join(OUT_DIR, fname)
    styles = make_styles()

    doc = BaseDocTemplate(
        fpath, pagesize=A4,
        leftMargin=22 * mm, rightMargin=22 * mm,
        topMargin=22 * mm, bottomMargin=20 * mm,
        title=ch["title"], author="요가 강사가 되기 전 알았더라면",
    )

    cover_frame = Frame(
        18 * mm, 30 * mm, A4[0] - 36 * mm, A4[1] - 60 * mm,
        leftPadding=10, rightPadding=10, topPadding=10, bottomPadding=10,
        showBoundary=0,
    )
    body_frame = Frame(
        doc.leftMargin, doc.bottomMargin,
        A4[0] - doc.leftMargin - doc.rightMargin,
        A4[1] - doc.topMargin - doc.bottomMargin,
        showBoundary=0,
    )

    doc.addPageTemplates([
        PageTemplate(id="cover", frames=[cover_frame],
                     onPage=lambda c, d: cover_page(c, d, ch)),
        PageTemplate(id="body", frames=[body_frame], onPage=body_page),
    ])

    story = []
    # 표지
    story.append(Spacer(1, 60 * mm))
    story.append(Paragraph("요가 강사가 되기 전 알았더라면", styles["cover_brand"]))
    story.append(Paragraph(f"Chapter {ch['no']:02d} / 20", styles["cover_no"]))
    story.append(Spacer(1, 18 * mm))
    story.append(Paragraph(ch["title"], styles["cover_title"]))
    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(ch["subtitle"], styles["cover_sub"]))
    story.append(Spacer(1, 60 * mm))
    story.append(Paragraph("요가 강사 입문 가이드 시리즈", styles["cover_footer"]))

    # 본문 페이지로 넘김
    story.append(PageBreak())

    story.append(Paragraph(f"CHAPTER {ch['no']:02d} · 20문답으로 풀어보는 요가 강사의 길",
                           styles["h_chapter"]))
    story.append(Paragraph(ch["title"], styles["h_title"]))
    story.append(Paragraph(ch["subtitle"], styles["h_sub"]))

    for para in ch["body"].split("\n\n"):
        text = para.strip().replace("\n", "<br/>")
        if not text:
            continue
        story.append(Paragraph(text, styles["body"]))

    story.append(Spacer(1, 4 * mm))
    story.append(Paragraph(f"&ldquo; {ch['quote']} &rdquo;", styles["quote"]))

    story.append(Paragraph("— 다음 챕터에서 만나요 —", styles["closing_label"]))
    story.append(Paragraph(
        "요가 강사가 되기 전 알았더라면 시리즈는<br/>입문에서 지속까지, 20개의 질문으로 이어집니다.",
        styles["closing_msg"]))

    doc.build(story)
    return fpath


