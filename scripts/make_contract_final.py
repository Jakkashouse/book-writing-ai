def _set_font(run, name="맑은 고딕", size=10, bold=False, color=None, italic=False):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.find(qn("w:rFonts"))
    if rFonts is None:
        rFonts = OxmlElement("w:rFonts")
        rPr.append(rFonts)
    rFonts.set(qn("w:eastAsia"), name)
    rFonts.set(qn("w:ascii"), name)
    rFonts.set(qn("w:hAnsi"), name)


def _shade_run(run, color_hex="FFF2CC"):
    """수정된 부분을 음영 표시(연한 노랑)."""
    rPr = run._element.get_or_add_rPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), color_hex)
    rPr.append(shd)


def title(doc, text, size=20):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _set_font(r, size=size, bold=True)
    p.paragraph_format.space_after = Pt(10)


def cover_line(doc, text, align=WD_ALIGN_PARAGRAPH.LEFT, size=12, bold=True, indent=0):
    p = doc.add_paragraph()
    p.alignment = align
    r = p.add_run(text)
    _set_font(r, size=size, bold=bold)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    p.paragraph_format.space_after = Pt(4)


def article_head(doc, text, modified=False):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _set_font(r, size=10.5, bold=True)
    if modified:
        _shade_run(r)
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(3)


def para(doc, runs, indent_cm=0.0, hanging_cm=0.0):
    """runs: [(text, modified_bool), ...] — modified=True면 음영."""
    p = doc.add_paragraph()
    for text, mod in runs:
        r = p.add_run(text)
        _set_font(r, size=10)
        if mod:
            _shade_run(r)
    p.paragraph_format.left_indent = Cm(indent_cm)
    if hanging_cm:
        p.paragraph_format.first_line_indent = Cm(-hanging_cm)
    p.paragraph_format.space_after = Pt(2)


def plain(doc, text, indent_cm=0.0, bold=False, size=10):
    p = doc.add_paragraph()
    r = p.add_run(text)
    _set_font(r, size=size, bold=bold)
    p.paragraph_format.left_indent = Cm(indent_cm)
    p.paragraph_format.space_after = Pt(2)
    return p


def blank(doc, pt=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(pt)


def page_break(doc):
    from docx.enum.text import WD_BREAK
    p = doc.add_paragraph()
    r = p.add_run()
    r.add_break(WD_BREAK.PAGE)


